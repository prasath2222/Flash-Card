def fetch_wiki_thumbs(titles_list):
    results = {}
    headers = {"User-Agent": "Mozilla/5.0 (SequentialMultilingualFlashcards/2.0; Educational App)"}
    # Batch in groups of 40
    for i in range(0, len(titles_list), 40):
        batch = titles_list[i:i+40]
        encoded = urllib.parse.quote("|".join(batch))
        url = f"https://en.wikipedia.org/w/api.php?action=query&titles={encoded}&prop=pageimages&piprop=thumbnail&pithumbsize=960&redirects=1&format=json"
        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                query = data.get("query", {})
                norm_map = {n["from"]: n["to"] for n in query.get("normalized", [])}
                redir_map = {r["from"]: r["to"] for r in query.get("redirects", [])}
                page_by_title = {}
                for p in query.get("pages", {}).values():
                    thumb = p.get("thumbnail", {}).get("source")
                    if thumb:
                        page_by_title[p.get("title")] = thumb
                for orig in batch:
                    t = norm_map.get(orig, orig)
                    t = redir_map.get(t, t)
                    if t in page_by_title:
                        results[orig] = page_by_title[t]
        except Exception as e:
            print("Error fetching batch:", e)
    return results

def search_wiki_single(query_str):
    headers = {"User-Agent": "Mozilla/5.0 (SequentialMultilingualFlashcards/2.0; Educational App)"}
    encoded = urllib.parse.quote(query_str)
    url = f"https://en.wikipedia.org/w/api.php?action=query&generator=search&gsrsearch={encoded}&gsrlimit=5&prop=pageimages&piprop=thumbnail&pithumbsize=960&format=json"
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            pages = data.get("query", {}).get("pages", {})
            # sort by index
            for p in sorted(pages.values(), key=lambda x: x.get("index", 99)):
                thumb = p.get("thumbnail", {}).get("source")
                if thumb and not thumb.endswith(".svg") and not thumb.endswith(".svg.png"):
                    return thumb
    except Exception as e:
        pass
    return None

