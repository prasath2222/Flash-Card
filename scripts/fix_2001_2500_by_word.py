missing_titles = sorted(set(t for t in WORD_TO_EXACT_WIKI.values() if t.lower() not in title_to_url))
print(f"Missing titles out of 500 words: {len(missing_titles)}")

headers = {"User-Agent": "VocabStudyApp/1.5 (https://vocabstudy.example.org; admin@vocabstudy.example.org)"}
for q in missing_titles:
    enc = urllib.parse.quote(f"filetype:bitmap {q}")
    url = f"https://commons.wikimedia.org/w/api.php?action=query&generator=search&gsrsearch={enc}&gsrnamespace=6&gsrlimit=4&prop=imageinfo&iiprop=url&iiurlwidth=960&format=json"
    req = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            pages = data.get("query", {}).get("pages", {})
            for p in sorted(pages.values(), key=lambda x: x.get("index", 99)):
                ii = (p.get("imageinfo") or [{}])[0]
                thumb = ii.get("thumburl") or ii.get("url")
                if thumb and ".svg" not in thumb.lower() and ".tif" not in thumb.lower() and ".pdf" not in thumb.lower():
                    title_to_url[q.lower()] = thumb
                    break
    except Exception as e:
        print("Commons err:", q, e)

